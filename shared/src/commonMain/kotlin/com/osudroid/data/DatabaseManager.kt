package com.osudroid.data

import androidx.room.ConstructedBy
import androidx.room.Database
import androidx.room.RoomDatabase
import androidx.room.RoomDatabaseConstructor
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import com.osudroid.OsuGameHost
import com.osudroid.settings.GameFolders
import kotlin.jvm.JvmStatic

// Ported from rimu! project

/**
 * The current schema version of the database. A database of another version is recreated: there
 * are no migrations, see [buildOsuDatabase].
 */
const val DATABASE_VERSION = 5

/**
 * The game's database, the same on every platform. Its DAOs suspend, as Room only implements those
 * outside Android.
 */
@Database(
    version = DATABASE_VERSION,
    entities = [
        BeatmapInfo::class,
        BeatmapOptions::class,
        ScoreInfo::class,
        BeatmapSetCollection::class,
        BeatmapSetCollection_BeatmapSetInfo::class,
        BlockArea::class,
        ModPreset::class
    ],
    exportSchema = false
)
@ConstructedBy(OsuDatabaseConstructor::class)
abstract class OsuDatabase : RoomDatabase() {

    abstract fun getBeatmapInfoTable(): IBeatmapInfoDAO

    abstract fun getBeatmapOptionsTable(): IBeatmapOptionsDAO

    abstract fun getBeatmapCollectionsTable(): IBeatmapCollectionsDAO

    abstract fun getScoreInfoTable(): IScoreInfoDAO

    abstract fun getBlockAreaTable(): IBlockAreaDAO

    abstract fun getModPresetTable(): IModPresetDAO
}

/**
 * Creates the [OsuDatabase], generated by Room for each platform.
 */
@Suppress("NO_ACTUAL_FOR_EXPECT", "KotlinNoActualForExpect")
expect object OsuDatabaseConstructor : RoomDatabaseConstructor<OsuDatabase> {
    override fun initialize(): OsuDatabase
}

/**
 * Finishes building the database, the same way on every platform: over the bundled SQLite, and
 * recreated if it's of another version, as there are no migrations.
 */
fun RoomDatabase.Builder<OsuDatabase>.buildOsuDatabase(): OsuDatabase =
    setDriver(BundledSQLiteDriver())
        .fallbackToDestructiveMigration(dropAllTables = true)
        .build()

/**
 * The osu!droid database manager.
 */
object DatabaseManager {

    /**
     * Get the beatmaps table DAO.
     */
    @JvmStatic
    val beatmapInfoTable
        get() = database.getBeatmapInfoTable()

    /**
     * Get the beatmap options table DAO.
     */
    @JvmStatic
    val beatmapOptionsTable
        get() = database.getBeatmapOptionsTable()

    /**
     * Get the beatmap collections table DAO.
     */
    @JvmStatic
    val beatmapCollectionsTable
        get() = database.getBeatmapCollectionsTable()

    /**
     * Get the score table DAO.
     */
    @JvmStatic
    val scoreInfoTable
        get() = database.getScoreInfoTable()

    /**
     * Get the block area table DAO.
     */
    @JvmStatic
    val blockAreaTable
        get() = database.getBlockAreaTable()

    /**
     * Get the mod preset table DAO.
     */
    @JvmStatic
    val modPresetTable
        get() = database.getModPresetTable()

    /**
     * The path to the database file.
     */
    @JvmStatic
    val databasePath: String
        get() = "${GameFolders.corePath}databases/room-${OsuGameHost.current.buildType}.db"

    /**
     * The database, set by the platform once it's open.
     */
    @JvmStatic
    lateinit var database: OsuDatabase

}
